# Builds release packages of git-purge-branches into an output directory: a
# Debian package, a pacman package and a tarball with the install layout. The
# files and their timestamps depend only on the sources and the date of their
# commit, so that a build can be reproduced. The pacman package also records
# the directories of its build, so only a build at the same paths reproduces
# it. The sources may be a checkout or an archive of one without git.

set -euo pipefail

# Status of a usage error, as for git and getopt
readonly USAGE_ERROR=2

readonly name=git-purge-branches

root_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
readonly root_dir

function Usage()
{
    cat <<USAGE
usage: ${0##*/} [--version=<version>] --output=<dir> <format>...

Formats: deb, pacman, tarball. The version defaults to that of the sources,
which version.sh reports. The manual pages must have been generated by
build-man-pages.sh.
USAGE
}

version=
output=
formats=()

while (($# > 0)); do
    case "$1" in
        --version=*)
            version="${1#--version=}"
            ;;
        --output=*)
            output="${1#--output=}"
            ;;
        -h | --help)
            Usage
            exit 0
            ;;
        -*)
            echo "error: unknown option '$1'" >&2
            Usage >&2
            exit "${USAGE_ERROR}"
            ;;
        *)
            formats+=("$1")
            ;;
    esac
    shift
done

if [[ -z ${version} ]]; then
    version="$("${root_dir}/scripts/version.sh" version)"
fi

# Debian versions start with a digit, and those of native packages, which have
# no Debian revision, contain no hyphen.
if [[ ${version} != [0-9]* ]]; then
    echo "error: expected a version that starts with a digit, got '${version}'" >&2
    exit "${USAGE_ERROR}"
fi

if [[ ${version} == *-* ]]; then
    echo "error: expected a version without a hyphen, got '${version}'" >&2
    exit "${USAGE_ERROR}"
fi

if [[ -z ${output} ]]; then
    echo "error: expected --output" >&2
    Usage >&2
    exit "${USAGE_ERROR}"
fi

# The functions that build the formats, all checked before any is built
builders=()

for format in "${formats[@]}"; do
    case "${format}" in
        deb)
            builders+=(BuildDeb)
            ;;
        tarball)
            builders+=(BuildTarball)
            ;;
        pacman)
            builders+=(BuildPacman)
            ;;
        *)
            echo "error: unknown format '${format}'" >&2
            Usage >&2
            exit "${USAGE_ERROR}"
            ;;
    esac
done

# The timestamps of the files in the packages, which makepkg reads and the
# changelog of the Debian package carries for dpkg-buildpackage
SOURCE_DATE_EPOCH="$("${root_dir}/scripts/version.sh" date)"
export SOURCE_DATE_EPOCH

# The maintainer of both packages
maintainer="$(sed -n 's/^Maintainer: //p' "${root_dir}/debian/control")"
readonly maintainer

staging="$(mktemp -d)"
readonly staging
trap 'rm -rf -- "${staging}"' EXIT

mkdir -p -- "${output}"
output="$(cd -- "${output}" && pwd)"
readonly output

# Copies the sources of a checkout or an archive into the given directory, so
# that the outputs of a build stay out of them. The copy lacks the repository
# of git and the outputs of the recipes.
function CopySources()
{
    local target="$1"

    install -d "${target}"
    tar --create --file="${staging}/sources.tar" --directory="${root_dir}" \
        --exclude=./.git --exclude=./dist --exclude=./man .
    tar --extract --file="${staging}/sources.tar" --directory="${target}"
}

# Runs the given command in the given directory with its output in a log,
# which it prints if the command fails.
function RunLogged()
{
    local directory="$1"
    shift

    (cd "${directory}" && "$@") > "${staging}/build.log" 2>&1 || {
        cat "${staging}/build.log" >&2
        return 1
    }
}

# Installs every component below the prefix in the given root directory.
function Stage()
{
    local root="$1"
    local prefix="$2"

    DESTDIR="${root}" "${root_dir}/scripts/install.sh" --prefix="${prefix}" \
        script man bash zsh fish
}

# Builds the Debian package with dpkg-buildpackage in a copy of the sources.
# The version of the package comes from the changelog, which the copy gets for
# the version to build. The build dependencies are not checked, since systems
# other than Debian lack the database of installed packages, and a missing tool
# fails the build anyway.
function BuildDeb()
{
    local source="${staging}/deb/${name}-${version}"
    local date

    CopySources "${source}"
    date="$(date --utc --rfc-email --date="@${SOURCE_DATE_EPOCH}")"
    cat > "${source}/debian/changelog" <<CHANGELOG
${name} (${version}) unstable; urgency=medium

  * Release ${version}.

 -- ${maintainer}  ${date}
CHANGELOG

    RunLogged "${source}" dpkg-buildpackage --build=binary --no-sign --no-check-builddeps
    mv "${staging}/deb/${name}_${version}_all.deb" "${output}/"
}

# Builds the pacman package with makepkg in a copy of the sources, with the
# version to build. The dependencies are not checked, since systems other than
# Arch lack the database of pacman, and a missing tool fails the build anyway.
function BuildPacman()
{
    local source="${staging}/pacman/${name}-${version}"

    CopySources "${source}"
    RunLogged "${source}" env GIT_PURGE_BRANCHES_VERSION="${version}" PACKAGER="${maintainer}" \
        PKGDEST="${output}" PKGEXT=.pkg.tar.zst BUILDDIR="${staging}/pacman/build" \
        SRCDEST="${staging}/pacman/sources" makepkg --nodeps -D pacman
}

function BuildTarball()
{
    local top="${name}-${version}"
    local root="${staging}/tarball"

    Stage "${root}/${top}" /
    install -D -m 0644 "${root_dir}/LICENSES/GPL-3.0-or-later.txt" \
        "${root}/${top}/share/doc/${name}/GPL-3.0-or-later.txt"

    tar --create --file="${output}/${top}.tar.gz" --directory="${root}" \
        --use-compress-program='gzip --best --no-name' --sort=name \
        --mtime="@${SOURCE_DATE_EPOCH}" --owner=root:0 --group=root:0 "${top}"
}

for builder in "${builders[@]}"; do
    "${builder}"
done
